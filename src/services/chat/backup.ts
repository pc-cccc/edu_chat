import { formatDate } from '../../utils/format.js'
import * as db from './db.js'
import { importHistoryInto, replaceHistory, useChatStore } from './store.js'
import type { Session } from './types.js'

export { BackupError } from './history/errors.js'

// 导入、导出与全部删除串行处理，避免读取归档时数据被清空或两个替换事务交错。
let backupQueue: Promise<unknown> = Promise.resolve()

const enqueueBackup = <T>(run: () => Promise<T>): Promise<T> => {
  const task = backupQueue.then(run)
  backupQueue = task.catch(() => {})
  return task
}

const backupFileName = (date: Date) => `deepseek_data-${formatDate(date)}.zip`

/** 导出为历史会话导出格式的 ZIP，可再次导入；传入 ids 时只导出这些会话。 */
export const exportHistory = (sessionIds?: string[]): Promise<{ name: string; blob: Blob }> =>
  enqueueBackup(async () => {
    // 列表和已加载内容保留导出开始时的快照；未打开的会话逐条读取，不填满详情缓存。
    const { sessions, sessionCache } = useChatStore.getState()
    const selected = sessionIds ? new Set(sessionIds) : null
    const list = selected ? sessions.filter((item) => selected.has(item.id)) : sessions
    async function* readSessions(): AsyncGenerator<Session> {
      for (const summary of list) {
        const session = Object.hasOwn(sessionCache, summary.id)
          ? sessionCache[summary.id]
          : await db.loadSession(summary.id)
        if (!session) {
          throw new Error(`History session disappeared during export: ${summary.id}`)
        }
        // 详情读取期间可能重命名，归档标题与开始时的列表保持一致。
        yield { ...session, ...summary }
      }
    }
    const { exportArchive } = await import('./history/exportArchive.js')
    const now = new Date()
    const blob = await exportArchive(readSessions())
    return { name: backupFileName(now), blob }
  })

export type ImportMode = 'merge' | 'replace'

export type ImportHistoryResult = { count: number; skipped: number }

/**
 * 确认后调用：先检查 ZIP 格式与版本，校验失败时保留正在生成的回答；
 * 通过后从 ZIP 流式写入暂存，成功才替换（replace）或并入（merge）原有会话与图片原件。
 * merge 保留现有历史：内容一致的会话跳过，同 ID 内容不同的保留为副本；count 为新加入的会话数。
 */
export const importHistory = (
  file: File,
  mode: ImportMode = 'replace'
): Promise<ImportHistoryResult> =>
  enqueueBackup(async () => {
    const { checkArchiveFormat, importArchive } = await import('./history/importArchive.js')
    await checkArchiveFormat(file)
    return importHistoryInto(() => importArchive(file, mode), { merge: mode === 'merge' })
  })

/** 确认删除后调用：以空历史原子替换全部本地会话与附件，保留 API Key 和其他设置。 */
export const clearHistory = (): Promise<void> =>
  enqueueBackup(async () => {
    await replaceHistory(async () => {})
  })
